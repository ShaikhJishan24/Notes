package firstprogram;

public class SwitchCase {

	public static void main(String[] args) {
		
		int num = 3;
		
		switch(num) {
		case 1 : 
			System.out.println(num);
			break;
		
		case 2 : 
			System.out.println(num);
			break;
		
		case 3 : 
			System.out.println("Hello " + num);
			break;
		
		case 4 : 
			System.out.println(num);
			break;
		
		case 5 : 
			System.out.println(num);
			break;
		
		
		}
	}

}
